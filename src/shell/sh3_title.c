/*
 * sh3_title.c: the title screen, TM2.EXE 0x004780fc (see sh3_title.h and sh3_screen.h for the
 * frame convention).
 *
 * The scene definition is the original's frame as it stands at each call, final values only.
 * The CD volume steps keep the original's frame slots (+0x5a0, +0x5a4) and its 32 bit wrap
 * (volume << 16) - volume before the signed division by 100. The second volume is the constant
 * 0, so its clamp to 0xffff (0x00478e9f) cannot be reached.
 */
#include "sh3_title.h"

#define R8(a) sh_r8(e, a)
#define R32(a) sh_r32(e, a)
#define W8(a, v) sh_w8(e, a, v)
#define W16(a, v) sh_w16(e, a, v)
#define W32(a, v) sh_w32(e, a, v)
#define FB(o) (fb + (uint32_t)(o))
#define F8(o, v) W8(FB(o), v)
#define F16(o, v) W16(FB(o), v)
#define F32(o, v) W32(FB(o), v)
#define C0(f) sh3_call(e, f, 0, 0, 0, 0, 0, 0)
#define C1(f, a) sh3_call(e, f, 1, a, 0, 0, 0, 0)
#define C2(f, a, b) sh3_call(e, f, 2, a, b, 0, 0, 0)
#define C3(f, a, b, c) sh3_call(e, f, 3, a, b, c, 0, 0)
#define C4(f, a, b, c, d) sh3_call(e, f, 4, a, b, c, d, 0)
#define C5(f, a, b, c, d, x) sh3_call(e, f, 5, a, b, c, d, x)

