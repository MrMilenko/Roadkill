/* the mixer value and the CD volume from a music volume, in the frame slot o */
static void cd_volume(const ShEnv* e, uint32_t fb, uint32_t o, uint32_t v) {
    F32(o, v);
    int32_t mn = (int32_t)R32(0x00c8507cu);
    W32(0x00c85098u, (uint32_t)((int32_t)v < mn ? mn : (int32_t)v));
    int32_t t = (int32_t)((v << 16) - v) / 100;
    F32(o, (uint32_t)t);
    if (t > 0xffff) F32(o, 0xffff);
    uint32_t c = R32(FB(o));
    F32(o, c + (c << 16));
    C2(0x004b8f48u, 0x00c850bcu, R32(FB(o)));   /* cd_set_volume */
}

static void audio_method(const ShEnv* e, int k) {
    uint32_t obj = R32(0x00626014u);
    C2(R32(R32(obj + 8) + 4 * k), obj, 0xb);
}

uint32_t sh3_title(const ShEnv* e, uint32_t fb) {
    C0(0x0046329cu);                 /* net_reset */
    C1(0x0046f918u, 0x1b);           /* soundStop */
    C0(0x0046f94cu);
    C0(0x0046f958u);
    C5(0x00469f08u, SH3_SCENE, 0x004780fcu, 0, 0x00477b90u, 0);    /* sceneInit */
    W32(0x0050fae8u, 0); W32(0x0050faecu, 0xfffffb50u); W32(0x0050faf0u, 0);
    W16(0x0050faf4u, 0); W16(0x0050faf6u, 0); W16(0x0050faf8u, 0);
    C3(0x00499408u, FB(0x134), 0x004e2839u, 1);
    C3(0x00469c40u, FB(0), FB(0x134), 0x2e630);
    layout(e, fb);
    static const uint16_t items[3] = {0x2b4, 0x260, 0x308};
    for (int i = 0; i < 3; i++) C2(0x0046a15cu, SH3_SCENE, FB(items[i]));
    C2(0x0046a138u, SH3_SCENE, FB(0x35c));
    sh3_add_actions(e, fb, actions, 38);
    C2(0x0046a324u, SH3_SCENE, 0x004e284cu);   /* scene resources */
    C1(0x00469c78u, FB(0));
    audio_method(e, 1);                        /* title music */
    cd_volume(e, fb, 0x5a0, C0(0x0046f9dcu));  /* music_volume_get */
    uint32_t r = C1(0x0046a5fcu, SH3_SCENE);   /* sceneRun */
    if (R8(0x0050fb1cu) == 3) {
        C1(0x0046fdf8u, R32(0x00c85098u));     /* audioFadeOutMusic */
    } else {
        C4(0x0046f8b0u, 0x1b, 0, 0, 0x63);     /* sound_play */
        C0(0x0046f94cu);
        C0(0x0046f958u);
    }
    audio_method(e, 2);                        /* music stop */
    cd_volume(e, fb, 0x5a4, 0);
    return r;
}
