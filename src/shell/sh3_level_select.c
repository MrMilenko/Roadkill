uint32_t sh3_level_select(const ShEnv* e, uint32_t fb, uint32_t prev) {
    for (int i = 0; i < 3; i++) F8(0x744 + i, R8(0x004e805cu + i));
    for (int i = 0; i < 3; i++) F8(0x740 + i, R8(0x004e8060u + i));
    C5(0x00469f08u, SH3_SCENE, 0x004780fcu, prev == FROM_SCREEN ? prev : 0x00478edcu, 0x00477b90u, 0);
    W32(0x0050fae8u, 0); W32(0x0050faecu, 0xfffff510u); W32(0x0050faf0u, 0);
    W16(0x0050faf4u, 0); W16(0x0050faf6u, 0); W16(0x0050faf8u, 0);
    C3(0x00499408u, FB(0x134), 0x004e2907u, 1);     /* the background file name */
    C3(0x00469c40u, FB(0), FB(0x134), 0x2e630);     /* image record */
    layout1(e, fb, prev == FROM_SCREEN ? prev : 0x0047baa0u);
    C0(0x00452d28u);
    uint8_t t = R8(GS_TYPE);
    layout2(e, fb, t == 3 ? 0 : 2);
    uint32_t src = (t == 5 || t == 6 || t == 7) ? FB(0x744) : FB(0x740);
    for (int i = 0; i < 3; i++) F8(0x518 + i, R8(src + i));
    layout3(e, fb);
    C2(0x0046a15cu, SH3_SCENE, FB(0x2c0));
    static const uint16_t decor[7] = {0x3b4, 0x314, 0x364, 0x260, 0x454, 0x404, 0x4a4};
    for (int i = 0; i < 7; i++) C2(0x0046a138u, SH3_SCENE, FB(decor[i]));
    sh3_add_actions(e, fb, actions, 72);
    C2(0x0046a324u, SH3_SCENE, 0x004e291eu);   /* scene resources "SHELLDB1\LEVELSEL" */
    C1(0x00469c78u, FB(0));
    uint32_t r = C1(0x0046a5fcu, SH3_SCENE);   /* sceneRun */
    uint8_t res = R8(0x0050fb1cu);
    if (res == 0) {
        uint8_t lv = (uint8_t)(C1(0x00469cdcu, FB(0x3b4)) + 1);
        W8(GS_LEVEL, lv);
        if (R8(GS_TYPE) == 3) {
            uint32_t n = C2(0x00474e0cu, 0x00624ea8u, (uint32_t)(int32_t)(int8_t)lv);
            W8(0x00624eaau, (uint8_t)((uint8_t)n - R8(0x00624ea9u)));
        }
    } else if (res == 4) {                     /* the secret level */
        W8(GS_LEVEL, (uint8_t)(R8(FB(0x51b)) + 10));
        C0(0x004ad848u);
        C4(0x00451f28u, 2, 0x13f, 0xef, 0x004e2930u);
        C0(0x00495b14u);
        r = prev == FROM_SCREEN ? prev : 0x0047baa0u;
    }
    F32(0x268, 0x004e5740u);
    C1(0x00452d48u, R8(FB(0x2b0)));            /* font color byte set */
    return r;
}
