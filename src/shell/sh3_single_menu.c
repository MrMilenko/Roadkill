uint32_t sh3_single_menu(const ShEnv* e, uint32_t fb) {
    while ((int32_t)C1(0x00499884u, 0x004e285bu) < 0) {    /* the game disc */
        if (C1(0x004bc660u, 0x16) != 4) return 0x004780fcu;     /* cdecl: the message box */
    }
    C5(0x00469f08u, SH3_SCENE, 0x004780fcu, 0x004780fcu, 0x00477b90u, 0);    /* sceneInit */
    W32(0x0050fae8u, 0); W32(0x0050faecu, 0xfffffb50u); W32(0x0050faf0u, 0);
    W16(0x0050faf4u, 0); W16(0x0050faf6u, 0); W16(0x0050faf8u, 0);
    C3(0x00499408u, FB(0x134), 0x004e2863u, 1);
    C3(0x00469c40u, FB(0), FB(0x134), 0x2e630);
    layout(e, fb);
    static const uint16_t items[3] = {0x308, 0x260, 0x2b4};
    static const uint16_t decor[3] = {0x3fc, 0x35c, 0x3ac};
    for (int i = 0; i < 3; i++) C2(0x0046a15cu, SH3_SCENE, FB(items[i]));
    for (int i = 0; i < 3; i++) C2(0x0046a138u, SH3_SCENE, FB(decor[i]));
    sh3_add_actions(e, fb, actions, 54);
    C2(0x0046a324u, SH3_SCENE, 0x004e2877u);   /* scene resources */
    C1(0x00469c78u, FB(0));
    uint32_t r = C1(0x0046a5fcu, SH3_SCENE);   /* sceneRun */
    if (R8(0x0050fb1cu)) return r;
    W8(0x00624ea9u, 1);
    for (uint32_t k = 1; k <= 13; k++) W8(0x00624eacu + k, 0xff);
    W8(0x00624eacu, 0);
    W8(0x00624eabu, 0);
    for (uint32_t k = 1; k <= 13; k++) W8(0x00624eb4u + k, 0xff);
    uint32_t sel = R32(0x0050fb94u + 4 * R32(0x0050fb20u));
    if (sel == FB(0x308)) {                    /* tournament */
        W8(0x00624ea8u, 1);
        W8(0x00624ec7u, 1);
        uint32_t n = C2(0x00474e0cu, 0x00624ea8u, 1);
        W8(0x00624eaau, (uint8_t)((uint8_t)n - R8(0x00624ea9u)));
        W8(0x00624ebfu, 3);
    } else if (sel == FB(0x260)) {             /* challenge */
        W8(0x00624ebfu, 1);
        W8(0x00624ea8u, 3);
    }
    return r;
}
